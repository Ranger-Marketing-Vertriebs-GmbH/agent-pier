import test from "node:test";
import assert from "node:assert/strict";
import { checkPythonLock } from "../../server/features/mcp-packages/python-lock-check.js";
import { lockDiff } from "../../server/features/mcp-packages/lock-check.js";

const h = (c) => c.repeat(64);
const ref = { registry: "pypi", name: "mcp-server-time", version: "2026.10.10" };
// The shape `uv pip compile --generate-hashes --no-header --no-annotate` writes.
const lock = (extra = "") => `mcp-server-time==2026.10.10 \\
    --hash=sha256:${h("a")} \\
    --hash=sha256:${h("b")}
Tzdata==2026.1 ; sys_platform != "emscripten" \\
    --hash=sha256:${h("c")}
${extra}`;
const foreign = { code: "MCP_PACKAGE_FOREIGN_SOURCE" };
const mismatch = { code: "MCP_PACKAGE_INTEGRITY_MISMATCH" };

test("a hashed PyPI lock yields normalised dependencies and its digest (D3: markers)", () => {
  const result = checkPythonLock(lock(), { ref, digests: [h("a"), h("b"), h("f")] });
  assert.deepEqual(result.dependencies, [
    { name: "mcp-server-time", version: "2026.10.10", path: "mcp-server-time" },
    { name: "tzdata", version: "2026.1", path: "tzdata" },
  ]);
  assert.match(result.digest, /^[0-9a-f]{64}$/);
  assert.equal(Object.keys(result).sort().join(), "dependencies,digest");
});

test("the digest is stable and changes with the lock text", () => {
  const a = checkPythonLock(lock(), { ref }).digest;
  assert.equal(checkPythonLock(lock(), { ref }).digest, a);
  const more = lock(`idna==3.10 \\\n    --hash=sha256:${h("d")}\n`);
  assert.notEqual(checkPythonLock(more, { ref }).digest, a);
});

test("names are PEP 503 normalised and versions canonical in the result", () => {
  const text = `MCP_Server.Time==2026.010.10 \\\n    --hash=sha256:${h("a")}\nTyping__Extensions==4.016.0 \\\n    --hash=sha256:${h("b")}\n`;
  assert.deepEqual(checkPythonLock(text, { ref }).dependencies, [
    { name: "mcp-server-time", version: "2026.10.10", path: "mcp-server-time" },
    { name: "typing-extensions", version: "4.16.0", path: "typing-extensions" },
  ]);
});

test("CRLF line endings and a missing final newline are accepted", () => {
  const text = lock().trimEnd().replace(/\n/g, "\r\n");
  assert.equal(checkPythonLock(text, { ref }).dependencies.length, 2);
});

test("lockDiff works unchanged on Python dependencies", () => {
  const before = checkPythonLock(lock(), { ref }).dependencies;
  const after = checkPythonLock(
    lock().replace("Tzdata==2026.1", "tzdata==2026.5") +
      `idna==3.10 \\\n    --hash=sha256:${h("d")}\n`,
    { ref },
  ).dependencies;
  assert.deepEqual(lockDiff(before, after), {
    added: [{ name: "idna", version: "3.10", path: "idna" }],
    removed: [],
    changed: [{ name: "tzdata", path: "tzdata", from: "2026.1", to: "2026.5" }],
  });
});

test("direct URLs, VCS, editable, option and extras lines are foreign (D3)", () => {
  for (const line of [
    `evil @ https://example.com/evil.whl \\\n    --hash=sha256:${h("d")}`,
    `evil@https://example.com/evil.whl \\\n    --hash=sha256:${h("d")}`,
    "-e git+https://github.com/a/b.git#egg=b",
    "--editable ./local",
    "-e .",
    "git+https://github.com/a/b.git@v1#egg=b",
    "https://example.com/c-1.0.tar.gz",
    "--extra-index-url https://example.com/simple",
    "--index-url https://example.com/simple",
    "-i https://example.com/simple",
    "--find-links /tmp",
    "-f /tmp",
    "--trusted-host example.com",
    "--no-binary :all:",
    "--pre",
    "-r other.txt",
    "-c /tmp/constraints.txt",
    `b @ file:///tmp/b.whl \\\n    --hash=sha256:${h("d")}`,
    `./wheels/b-1.0-py3-none-any.whl \\\n    --hash=sha256:${h("d")}`,
    `/tmp/b-1.0.tar.gz \\\n    --hash=sha256:${h("d")}`,
    `rich[jupyter]==14.0 \\\n    --hash=sha256:${h("d")}`,
    `rich [jupyter]==14.0 \\\n    --hash=sha256:${h("d")}`,
    `c==1.0 --hash=sha256:${h("d")}`,
    `c==1.0 ; python_version >= "3.11" @ https://x \\\n    --hash=sha256:${h("d")}`,
    `c==1.0 ; sys_platform == "/tmp/x" \\\n    --hash=sha256:${h("d")}`,
  ])
    assert.throws(() => checkPythonLock(lock(line), { ref }), foreign, line);
});

test("anything but an exact `==` pin of a public version is foreign", () => {
  for (const req of [
    "c>=1.0",
    "c~=1.0",
    "c===1.0",
    "c!=1.0",
    "c==1.*",
    "c==1.0,<2",
    "c",
    "c==",
    "c==1.0+local",
    "c==1.0+cpu.1",
    "c==latest",
    "c == 1.0",
    "-c==1.0",
    ".c==1.0",
    "c-==1.0",
  ])
    assert.throws(
      () => checkPythonLock(lock(`${req} \\\n    --hash=sha256:${h("d")}`), { ref }),
      foreign,
      req,
    );
});

test("comment lines are refused: the stored lock never carries paths", () => {
  for (const line of [
    "# via -r /tmp/stage/requirements.in",
    "    # via mcp-server-time",
    "# This file was autogenerated by uv via the following command:",
    "#    uv pip compile --python /Users/x/AgentPier/cpython/bin/python3",
    "#",
  ])
    assert.throws(() => checkPythonLock(lock(line), { ref }), foreign, line);
  assert.throws(
    () =>
      checkPythonLock(lock(`idna==3.10 \\\n    --hash=sha256:${h("d")}  # /tmp/x`), {
        ref,
      }),
    foreign,
  );
  assert.throws(
    () =>
      checkPythonLock(lock(`idna==3.10  # /tmp/x \\\n    --hash=sha256:${h("d")}`), {
        ref,
      }),
    foreign,
  );
});

test("a package without a sha256 hash is refused", () => {
  assert.throws(() => checkPythonLock(lock("idna==3.10"), { ref }), foreign);
  assert.throws(
    () =>
      checkPythonLock(lock(`idna==3.10 \\\n    --hash=md5:${"a".repeat(32)}`), { ref }),
    foreign,
  );
  for (const bad of [
    `--hash=sha256:${"a".repeat(63)}`,
    `--hash=sha256:${"a".repeat(65)}`,
    `--hash=sha256:${"A".repeat(64)}`,
    `--hash=sha256:${"g".repeat(64)}`,
    `--hash=sha512:${"a".repeat(128)}`,
    `--hash sha256:${h("d")}`,
    `--hash=sha256:${h("d")} --hash=sha256:${h("e")}`,
  ])
    assert.throws(
      () => checkPythonLock(lock(`idna==3.10 \\\n    ${bad}`), { ref }),
      foreign,
      bad,
    );
});

test("continuation structure is enforced", () => {
  // A dangling continuation joins the next requirement into one pip line.
  assert.throws(
    () =>
      checkPythonLock(lock(`idna==3.10 \\\nsix==1.0 \\\n    --hash=sha256:${h("d")}`), {
        ref,
      }),
    foreign,
  );
  // A hash after an entry has ended belongs to no requirement.
  assert.throws(
    () =>
      checkPythonLock(
        lock(`idna==3.10 \\\n    --hash=sha256:${h("d")}\n    --hash=sha256:${h("e")}`),
        {
          ref,
        },
      ),
    foreign,
  );
  // A hash before any requirement.
  assert.throws(
    () => checkPythonLock(`    --hash=sha256:${h("d")}\n${lock()}`, { ref }),
    foreign,
  );
  // The lock must not end inside a continuation.
  assert.throws(
    () =>
      checkPythonLock(lock(`idna==3.10 \\\n    --hash=sha256:${h("d")} \\\n`), { ref }),
    foreign,
  );
  // A blank line inside a continuation.
  assert.throws(
    () => checkPythonLock(lock(`idna==3.10 \\\n\n    --hash=sha256:${h("d")}`), { ref }),
    foreign,
  );
});

test("a package listed twice (also in another spelling) is refused", () => {
  assert.throws(
    () =>
      checkPythonLock(lock(`tzdata==2026.2 \\\n    --hash=sha256:${h("d")}`), { ref }),
    foreign,
  );
  assert.throws(
    () =>
      checkPythonLock(lock(`MCP.Server_Time==1.0 \\\n    --hash=sha256:${h("d")}`), {
        ref,
      }),
    foreign,
  );
});

test("top-level hashes must come from the PyPI release; versions compare canonically", () => {
  assert.throws(() => checkPythonLock(lock(), { ref, digests: [h("a")] }), mismatch);
  assert.throws(() => checkPythonLock(lock(), { ref, digests: [] }), mismatch);
  assert.throws(
    () => checkPythonLock(lock(), { ref: { ...ref, version: "1.0" } }),
    mismatch,
  );
  assert.equal(
    checkPythonLock(lock(), { ref: { ...ref, version: "2026.010.10" } }).dependencies
      .length,
    2,
  );
  // Only the root package's hashes are compared with the release digests.
  assert.equal(
    checkPythonLock(lock(), { ref, digests: [h("a"), h("b")] }).dependencies.length,
    2,
  );
});

test("the root package must be in the lock", () => {
  assert.throws(
    () => checkPythonLock(lock(), { ref: { ...ref, name: "other-server" } }),
    mismatch,
  );
  assert.throws(() => checkPythonLock("", { ref }), mismatch);
  assert.equal(
    checkPythonLock(lock(), { ref: { ...ref, name: "MCP_Server.Time" } }).dependencies
      .length,
    2,
  );
});

test("errors carry only a code and catalog text, never lock content", () => {
  const secret = "/Users/secret/AgentPier/stage";
  for (const text of [
    lock(`# via -r ${secret}/req.in`),
    lock(`b @ file://${secret}/b.whl`),
  ]) {
    try {
      checkPythonLock(text, { ref });
      assert.fail("expected a refusal");
    } catch (error) {
      assert.equal(error.code, "MCP_PACKAGE_FOREIGN_SOURCE");
      assert.equal(error.message.includes(secret), false);
      assert.equal(error.message.includes("file:"), false);
    }
  }
});

test("a lock that is not text is an install failure", () => {
  for (const text of [null, undefined, 42, {}, Buffer.from(lock())])
    assert.throws(() => checkPythonLock(text, { ref }), {
      code: "MCP_PACKAGE_INSTALL_FAILED",
    });
});
